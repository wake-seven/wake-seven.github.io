import assert from 'node:assert/strict';
import { createDevelopmentRuntime } from '../src/main.mjs';
import { createPersistence } from '../src/state/persistence.mjs';
import { createBoardQuizCatalog } from '../src/data/board-quiz.mjs';
import { createMessageCatalog } from '../src/data/messages.mjs';
import { createSatoriCatalog } from '../src/data/satori.mjs';
import { createBoardCommands } from '../src/commands/board-commands.mjs';
import { createProgressionCommands } from '../src/commands/progression-commands.mjs';
import { createBoardView } from '../src/ui/board.mjs';
import { createMessagePresenter } from '../src/ui/messages.mjs';
import { createNavigationController } from '../src/ui/navigation.mjs';
import { createRenderCoordinator } from '../src/ui/render.mjs';
import { createSpeedUnlockService } from '../src/runtime/progression.mjs';

const runtime = createDevelopmentRuntime({ triangles: [{ cells: [0, 1, 2] }] });
assert.equal(runtime.board.stateCount, 2187);
assert.equal(typeof runtime.settings.initialize, 'function');
assert.equal(typeof runtime.audio.playTone, 'function');
assert.equal(typeof runtime.speedUnlocks.initialize, 'function');
const board = Uint8Array.from([0, 1, 2, 0, 1, 2, 1]);
assert.deepEqual(Array.from(runtime.board.decode(runtime.board.encode(board))), Array.from(board));
assert.deepEqual(Array.from(runtime.board.roll(runtime.board.roll(board, 0, 1), 0, -1)), Array.from(board));
assert.deepEqual(Array.from(runtime.board.swipe(runtime.board.swipe(board, 0, 1), 0, -1)), Array.from(board));
assert.deepEqual(Array.from(runtime.board.click(runtime.board.click(board, 0, 1), 0, -1)), Array.from(board));
assert.equal(runtime.progression.indexFor({ mode: 'mastery', masteryIndex: 4 }), 4);
assert.equal(runtime.progression.uiPolicy({ mode: 'tutorial' }).assisted, true);
let notified = false;
const unsubscribe = runtime.store.subscribe(() => { notified = true; });
runtime.store.update({ navigation: { mode: 'tutorial', lap: 1 } });
runtime.store.updateSection('settings', { language: 'ja' });
assert.equal(runtime.store.state.settings.language, 'ja');
unsubscribe();
assert.equal(notified, true);
const memory = new Map();
const storage = { getItem: key => memory.get(key) ?? null, setItem: (key, value) => memory.set(key, value) };
const persistence = createPersistence({ storage, create: value => value });
assert.equal(persistence.write({ version: 1, ok: true }), true);
assert.deepEqual(persistence.read(), { version: 1, ok: true });
const messages = createMessageCatalog({ welcome: { dialog: 'trainingWelcome' }, lesson: { tip: { ja: 'ok' } } });
assert.equal(messages.has('welcome'), true);
assert.equal(messages.descriptor('welcome').timing, 'afterClear');
const satori = createSatoriCatalog([{ state: 4, par: 2 }, { state: 7, par: 3 }]);
assert.deepEqual(satori.byDepth(2), [{ state: 4, par: 2 }]);
const quiz = createBoardQuizCatalog({ ja: { title: '盤面クイズ' } });
assert.equal(quiz.forLanguage('en').title, '盤面クイズ');
const runtimeData = createDevelopmentRuntime({ data: { clearContent: { x: { tip: { ja: 'x' } } }, satoriStages: [{ state: 0, par: 1 }], boardQuizCopy: { ja: { title: 'q' } } } }).data;
assert.equal(runtimeData.messages.has('x'), true);
assert.equal(runtimeData.satori.length, 1);
assert.equal(runtimeData.boardQuiz.forLanguage('ja').title, 'q');
let boardState = Uint8Array.from([0, 0, 0]);
const boardCommands = createBoardCommands({
  getBoard: () => boardState,
  applyMove: (current, triangleIndex, direction) => ({ board: Uint8Array.from(current, value => value + direction), triangleIndex }),
  setBoard: next => { boardState = next; }
});
assert.equal(boardCommands.apply(0, 1).triangleIndex, 0);
assert.deepEqual(Array.from(boardState), [1, 1, 1]);
let progressionCalls = 0;
const progressionCommands = createProgressionCommands({ startSpeedRun: () => { progressionCalls++; return { ok: true }; } });
assert.deepEqual(progressionCommands.startSpeedRun(), { ok: true });
assert.equal(progressionCalls, 1);
assert.equal(createBoardView({}).build(), false);
assert.equal(createMessagePresenter({}).show('missing'), null);
const navigation = createNavigationController({ store: runtime.store, normalize: runtime.progression.normalizeNavigation });
assert.equal(navigation.setMode('tutorial', { tutorialStep: 2 }).ok, true);
assert.equal(runtime.store.state.navigation.mode, 'tutorial');
assert.equal(runtime.commands.progression.navigate({ mode: 'stage', stageIndex: 3 }).ok, true);
assert.equal(runtime.store.state.navigation.stageIndex, 3);
let renderCount = 0;
const renderer = createRenderCoordinator({ store: runtime.store, renderers: { navigation: () => { renderCount++; } } });
assert.equal(renderer.render().ok, true);
const disconnect = renderer.connect();
runtime.store.updateSection('navigation', { stageIndex: 4 });
disconnect();
assert.equal(renderCount, 2);
console.log('Validated development ES module entry point.');
